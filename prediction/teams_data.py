def _build_team(name: str, raw: tuple) -> TeamStats:
    (conf, w, l, ppg, papg, ypp_off, ypp_def,
     to_margin, third, rz, sacks, pen, sos, elo) = raw
    return TeamStats(
        name=name,
        conference=conf,
        wins=w,
        losses=l,
        points_per_game=ppg,
        points_allowed_per_game=papg,
        yards_per_play=ypp_off,
        yards_per_play_allowed=ypp_def,
        turnover_margin=to_margin,
        third_down_pct=third,
        red_zone_pct=rz,
        sacks_per_game=sacks,
        penalty_yards_per_game=float(pen),
        strength_of_schedule=sos,
        elo_rating=float(elo),
    )


_TEAMS_CACHE: dict[str, TeamStats] = {}


def _ensure_cache() -> dict[str, TeamStats]:
    if not _TEAMS_CACHE:
        for name, raw in _RAW.items():
            _TEAMS_CACHE[name] = _build_team(name, raw)
    return _TEAMS_CACHE


def get_team(name: str) -> TeamStats:
    teams = _ensure_cache()
    if name not in teams:
        raise KeyError(f"Team '{name}' not found. Use get_all_team_names() for the full list.")
    return teams[name]


def get_all_team_names() -> list[str]:
    return sorted(_RAW.keys())


def get_teams_by_conference(conference: str) -> list[str]:
    return sorted(name for name, raw in _RAW.items() if raw[0] == conference)


def get_conferences() -> list[str]:
    return sorted({raw[0] for raw in _RAW.values()})
